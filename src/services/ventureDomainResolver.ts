function makeMarketGap(
  id: string,
  title: string,
  unresolvedNeed: string,
  currentMarketShortcoming: string,
  opportunityAngle: string,
  demandLevel: 'High' | 'Medium' | 'Emerging' = 'High',
  competitionLevel: 'Low' | 'Moderate' | 'Crowded' = 'Low',
  quadrant: 'prime_opportunity' | 'crowded' | 'niche' | 'low_priority' = 'prime_opportunity',
  confidence: 'High' | 'Medium' | 'Low' = 'High'
): MarketOpportunityGap {
  return {
    id,
    title,
    unresolvedNeed,
    currentMarketShortcoming,
    opportunityAngle,
    demandLevel,
    competitionLevel,
    quadrant,
    confidence,
    provenance: 'ASSUMPTION',
    underservedAspect: unresolvedNeed,
    whyItMatters: currentMarketShortcoming,
    supportingEvidence: 'Venture domain analysis & segment mapping',
    competitorsAddressing: [],
    unresolvedElement: unresolvedNeed,
    whatToValidateNext: `Validate ${title.toLowerCase()} with prospective users.`,
  };
}

export function detectVentureDomain(
  idea: Partial<IdeaData>,
  businessModel: Partial<BusinessModelData>,
  project: Partial<ProjectMetadata>
): VentureDomainType {
  const text = `${project.name || ''} ${idea.rawInput || ''} ${idea.problem || ''} ${idea.targetAudience || ''} ${idea.differentiation || ''}`.toLowerCase();

  // Test A: Tutoring / EdTech
  if (
    text.includes('tutor') ||
    (text.includes('student') && (text.includes('college') || text.includes('study') || text.includes('peer') || text.includes('teach') || text.includes('academic') || text.includes('affordable'))) ||
    text.includes('edtech') ||
    text.includes('course')
  ) {
    return 'tutoring_edtech';
  }

  // Test B: Skincare / Beauty / Cosmetics
  if (
    text.includes('skincare') ||
    text.includes('skin care') ||
    text.includes('cosmetic') ||
    text.includes('serum') ||
    text.includes('lotion') ||
    text.includes('dermatol') ||
    (text.includes('beauty') && text.includes('brand')) ||
    (text.includes('sustainable') && text.includes('skin'))
  ) {
    return 'skincare_beauty';
  }

  // Test C: Food Marketplace / Corporate Lunch Orders
  if (
    (text.includes('restaurant') || text.includes('kitchen') || text.includes('lunch') || text.includes('meal') || text.includes('catering')) &&
    (text.includes('corporate') || text.includes('office') || text.includes('recurring') || text.includes('b2b') || text.includes('workplace') || text.includes('employee'))
  ) {
    return 'food_catering_marketplace';
  }

  // Food Waste AI
  if (
    (text.includes('waste') || text.includes('spoilage') || text.includes('surplus') || text.includes('predict') || text.includes('demand')) &&
    (text.includes('restaurant') || text.includes('food') || text.includes('kitchen'))
  ) {
    return 'food_waste_ai';
  }

  // Restaurant Hospitality Tech
  if (
    text.includes('restaurant') ||
    text.includes('dine') ||
    text.includes('waiter') ||
    text.includes('kitchen order') ||
    text.includes('pos') ||
    text.includes('table qr')
  ) {
    return 'restaurant_hospitality';
  }

  // Water bottle / Sustainable drinkware
  if (
    text.includes('water bottle') ||
    text.includes('drinkware') ||
    text.includes('tumbler') ||
    text.includes('hydration') ||
    text.includes('flask')
  ) {
    return 'water_bottle_sustainable';
  }

  // General classifications based on productType
  if (businessModel.productType === 'physical') {
    return 'd2c_physical';
  }

  if (businessModel.productType === 'marketplace' || text.includes('marketplace') || text.includes('two-sided')) {
    return 'marketplace_general';
  }

  if (businessModel.productType === 'saas' || text.includes('saas') || text.includes('software') || text.includes('ai platform')) {
    return 'b2b_saas';
  }

  return 'generic_venture';
}

export function resolveVentureDomainProfile(
  idea: IdeaData,
  businessModel: BusinessModelData,
  project: ProjectMetadata
): ResolvedDomainProfile {
  const domainType = detectVentureDomain(idea, businessModel, project);
  const ventureName = idea.name || project.name || 'Untitled Venture';
  const targetAudience = idea.targetAudience || 'Target customers and early adopters';
  const problem = idea.problem || idea.rawInput || 'Status-quo friction with legacy alternatives';
  const differentiator = idea.differentiation || 'Proprietary specialized mechanism and transparent execution';

  switch (domainType) {
    case 'tutoring_edtech':
      return createTutoringEdTechProfile(ventureName, targetAudience, problem, differentiator);

    case 'skincare_beauty':
      return createSkincareBeautyProfile(ventureName, targetAudience, problem, differentiator);

    case 'food_catering_marketplace':
      return createFoodCateringMarketplaceProfile(ventureName, targetAudience, problem, differentiator);

    case 'food_waste_ai':
      return createFoodWasteAiProfile(ventureName, targetAudience, problem, differentiator);

    case 'water_bottle_sustainable':
      return createWaterBottleProfile(ventureName, targetAudience, problem, differentiator);

    case 'd2c_physical':
      return createD2CPhysicalProfile(ventureName, targetAudience, problem, differentiator);

    case 'marketplace_general':
      return createMarketplaceProfile(ventureName, targetAudience, problem, differentiator);

    case 'b2b_saas':
      return createB2BSaaSProfile(ventureName, targetAudience, problem, differentiator);

    case 'restaurant_hospitality':
      return createRestaurantHospitalityProfile(ventureName, targetAudience, problem, differentiator);

    case 'generic_venture':
    default:
      return createGenericVentureProfile(ventureName, targetAudience, problem, differentiator, businessModel.productType || undefined);
  }
}

